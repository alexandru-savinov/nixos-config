#!/usr/bin/env bash
# Arms for modules/services/sancta-soc-page.sh, driven with stub generator and
# gate. Usage: sancta-soc-page-arms.sh <path to the wrapper>
# Needs on PATH: bash, node, jq, flock (util-linux), sha256sum (coreutils).
# Used by tests/sancta-soc-page.nix (Linux build) and runnable by hand:
#   nix shell nixpkgs#{nodejs,jq,util-linux,coreutils} -c \
#     bash tests/sancta-soc-page-arms.sh modules/services/sancta-soc-page.sh
set -u
WRAPPER=${1:?usage: $0 <wrapper>}
WRAPPER=$(cd "$(dirname "$WRAPPER")" && pwd)/$(basename "$WRAPPER")
[ -r "$WRAPPER" ] || { echo "SELF-TEST FAILED: cannot read wrapper $WRAPPER" >&2; exit 1; }
echo "driving the real wrapper: $WRAPPER"
work=$(mktemp -d)
cd "$work"
# The wrapper generates and gates under $TMPDIR; keep it OUTSIDE the gallery dir.
export TMPDIR="$work/tmp"; mkdir -p "$TMPDIR"
idx=$PWD/idx; o=$PWD/o
mkdir -p "$idx/gallery" "$o"

# Stub generator: MODE picks the branch.
cat > "$idx/gallery/soc.mjs" <<'EOF'
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
const out = process.argv[process.argv.indexOf('--out') + 1];
const mode = process.env.MODE;
if (mode === 'genfail') process.exit(1);
const MARK = 'SYNTH-UNGATED-MARKER-7f3a9c';
writeFileSync(out, mode === 'leak-main' ? 'LEAK new soc\n' : mode === 'hang' ? `new soc ${MARK}\n` : 'new soc\n');
if (mode !== 'no-decide') writeFileSync(join(dirname(out), 'soc-decide.html'),
  mode === 'leak-decide' ? 'LEAK new decide\n' : mode === 'closed-decide' ? 'CLOSED\n' : mode === 'hang' ? `new decide ${MARK}\n` : 'new decide\n');
EOF

# Stub gate, same exit contract as gallery/publish.mjs.
cat > "$idx/gallery/publish.mjs" <<'EOF'
import { readFileSync, writeFileSync } from 'node:fs';
import { basename } from 'node:path';
import { createHash } from 'node:crypto';
const f = process.argv[2];
const b = readFileSync(f);
if (process.env.MODE === 'hang') {
  // Generation is done, approval is not: announce, then wait to be killed.
  writeFileSync(process.env.HANG_FLAG, String(process.pid));
  Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 600000);
}
if (b.includes('CLOSED')) process.exit(2);
if (b.includes('LEAK')) process.exit(1);
writeFileSync(f + '.passed', JSON.stringify({ img: basename(f), sha256: createHash('sha256').update(b).digest('hex') }) + '\n');
EOF

seed() {
  rm -rf "$o"; mkdir -p "$o"
  for p in soc.html soc-decide.html; do
    echo "old $p" > "$o/$p"; echo '{"sha256":"old"}' > "$o/$p.passed"
  done
  # An orphan stage left by a SIGKILLed run: every arm must sweep it.
  mkdir -p "$o/.soc-stage.orphan"; echo stale > "$o/.soc-stage.orphan/soc.html"
}
snap() { (cd "$o" && ls -A | grep -v '^\.soc-stage' | sort && cat ./*) | sha256sum; }

fail=0
# arm <name> <MODE> <want exit> <want: same|promoted>
arm() {
  seed; local before; before=$(snap)
  local rc=0
  MODE="$2" SANCTA_SOC_INDEX="$idx" SANCTA_SOC_OUT_DIR="$o" bash "$WRAPPER" > log 2>&1 || rc=$?
  local after; after=$(snap)
  local ok=1
  [ "$rc" -eq "$3" ] || ok=0
  if [ "$4" = same ]; then
    [ "$before" = "$after" ] || ok=0
  else
    for p in soc.html soc-decide.html; do
      grep -q '^new' "$o/$p" || ok=0
      [ "$(jq -r .sha256 "$o/$p.passed")" = "$(sha256sum "$o/$p" | cut -d' ' -f1)" ] || ok=0
    done
  fi
  # The stage directory must never outlive a run, pass or fail.
  if ls -A "$o" | grep -q '^\.soc-stage'; then ok=0; fi
  if [ "$ok" = 1 ]; then echo "ok   $1 (exit $rc)"; else
    echo "FAIL $1: exit $rc (want $3), want $4" >&2; sed 's/^/    | /' log >&2; ls -A "$o" >&2; fail=1; fi
}

arm "both pages pass -> both promoted with matching tokens" pass 0 promoted
arm "gate FAIL on soc.html -> nothing replaced" leak-main 1 same
arm "gate FAIL on soc-decide only -> soc.html NOT promoted either" leak-decide 1 same
arm "gate CLOSED -> nothing replaced, exit 2 kept" closed-decide 2 same
arm "generator fails closed -> nothing replaced" genfail 1 same
arm "generator omits soc-decide -> nothing replaced" no-decide 2 same

# (a) A producer killed after generation and before approval leaves no
# generated byte anywhere under the gallery tree. The gate stub announces it is
# reached (both pages already generated), then blocks; we SIGKILL the wrapper
# and the gate, so no EXIT trap runs. A marker generated into the pages must
# not be found by grepping the whole gallery tree.
kill_arm() {
  seed
  local flag="$PWD/hang.flag" ok=1 wpid gpid
  rm -f "$flag"
  MODE=hang HANG_FLAG="$flag" SANCTA_SOC_INDEX="$idx" SANCTA_SOC_OUT_DIR="$o" \
    bash "$WRAPPER" > log 2>&1 &
  wpid=$!
  for _ in $(seq 1 200); do [ -s "$flag" ] && break; sleep 0.1; done
  if [ ! -s "$flag" ]; then ok=0; echo "gate stub never reached" >&2; fi
  gpid=$(cat "$flag" 2>/dev/null || true)
  # Generation really happened: the marker exists in the work dir (proves the
  # grep below is able to find it, i.e. the arm is not vacuous).
  grep -rq "$MARKER" "$TMPDIR" || { ok=0; echo "marker not generated (vacuous arm)" >&2; }
  kill -9 "$wpid" ${gpid:+"$gpid"} 2>/dev/null || true
  wait "$wpid" 2>/dev/null || true
  if grep -rq "$MARKER" "$o"; then ok=0; echo "marker found under gallery:" >&2; grep -rl "$MARKER" "$o" >&2; fi
  # Served files untouched by the killed run.
  [ "$(cat "$o/soc.html")" = "old soc.html" ] || ok=0
  if [ "$ok" = 1 ]; then echo "ok   killed before approval -> no generated bytes under gallery"; else
    echo "FAIL killed before approval" >&2; fail=1; fi
}
MARKER=SYNTH-UNGATED-MARKER-7f3a9c
kill_arm

# (b) the successful run, already asserted by the first arm: both pages
# published with tokens whose sha256 equals the bytes on disk. Asserted once
# more here against the exact content, so the proof does not depend on arm order.
seed
MODE=pass SANCTA_SOC_INDEX="$idx" SANCTA_SOC_OUT_DIR="$o" bash "$WRAPPER" > log 2>&1 || { fail=1; echo "FAIL success run" >&2; }
b_ok=1
[ "$(cat "$o/soc.html")" = "new soc" ] || b_ok=0
[ "$(cat "$o/soc-decide.html")" = "new decide" ] || b_ok=0
for p in soc.html soc-decide.html; do
  [ "$(jq -r .sha256 "$o/$p.passed")" = "$(sha256sum "$o/$p" | cut -d' ' -f1)" ] || b_ok=0
  [ "$(jq -r .img "$o/$p.passed")" = "$p" ] || b_ok=0
done
if [ "$b_ok" = 1 ]; then echo "ok   success run publishes both pages with matching tokens"; else echo "FAIL success run content" >&2; fail=1; fi

[ "$fail" = 0 ] || exit 1
echo "sancta-soc-page: all arms passed"
